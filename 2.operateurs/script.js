// operateurs

// 1. Opérateurs arithmétiques


// - Addition : +
 let a = 5 + 3; // 8


// - Soustraction : -
 let b = 5 - 3; // 2


// - Multiplication : *
 let c = 5 * 3; // 15


// - Division : /
 let d = 5 / 3; // 1.6666666666666667

// - Modulo : % (reste de la division entière)
 let e = 5 % 3; // 2


// - Exponentiation : ** (puissance)
 let f = 5 ** 3; // 125


// 2. Opérateurs de comparaison


// - Égalité : == (valeur égale)
 let a2 = 5 == 5; // true


// - Égalité stricte : === (valeur et type égaux)
 let b2 = 5 === 5; // true


// - Inégalité : != (valeur différente)
 let c2 = 5 != 3; // true



// - Inégalité stricte : !== (valeur et type différents)
let d2 = 5 !== "5"; // true


// - Supérieur : >
let e2 = 5 > 3; // true


// - Supérieur ou égal : >=
let f2 = 5 >= 5; // true


// - Inférieur : <
let g = 5 < 3; // false


// - Inférieur ou égal : <=
let h = 5 <= 5; // true


// 3. Opérateurs logiques


// - ET logique : && (et)
 let a3 = true && false; // false


// - OU logique : || (ou)
let b3 = true || false; // true



// - NON logique : ! (non)
let c3 = !true; // false
